// ============================================================================
// DPDP checker: the registry
// ----------------------------------------------------------------------------
// One entry per check ID. A check may run in several modes:
//   static       a function over the repository's files (npm run dpdp:check)
//   db           a named check in supabase/tests/dpdp_probe.sql, which CI runs;
//                the static run confirms the probe holds that check
//   runtime      a function over live settings and counts (the checker tab)
//   attestation  owner confirmations recorded in Settings
//
// Titles state the rule that is met (rules/disclosure.md §3).
// ============================================================================

export interface CheckDefinition {
  id: string
  title: string
  ref: string
  area: CheckArea
  modes: CheckMode[]
  required: boolean
  howToFix: string
  static?: StaticCheck
  /** The name of the dpdp_probe.sql check(s) that hold this rule. */
  probe?: string[]
  runtime?: RuntimeCheck<ComplianceSnapshot>
  attestations?: string[]
}

